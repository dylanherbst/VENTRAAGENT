'use client';
import { useEffect, useMemo, useRef, useState } from 'react';
import { blankPost, contentBodyLimit, contentCalendarStorageKey, contentPlatforms, contentStatuses, contentTitleLimit, countsByStatus, groupByMonthAndDay, persistContentCalendar, platformGuidance, removePost, restoreContentCalendar, savePost, validatePost } from '../../lib/local-content-calendar';
import type { ContentPost, ContentStatus } from '../../lib/local-content-calendar';
import { offerStorageKey, restoreLocalOffers } from '../../lib/local-offers';
import type { LocalOffer } from '../../lib/local-offers';
import type { Profile } from '../../lib/onboarding';

const statusLabel: Record<ContentStatus, string> = { idea: 'Idea', drafted: 'Drafted', ready: 'Ready', 'posted-manually': 'Posted manually' };
const newId = () => (typeof crypto !== 'undefined' && 'randomUUID' in crypto ? crypto.randomUUID() : `post-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`);

export default function ContentCalendar({ profile }: { profile: Profile }) {
  const profileId = profile.id;
  const [posts, setPosts] = useState<ContentPost[]>([]);
  const [offers, setOffers] = useState<LocalOffer[]>([]);
  const [editing, setEditing] = useState<ContentPost | null>(null);
  const [filter, setFilter] = useState<'all' | ContentStatus>('all');
  const [ready, setReady] = useState(false);
  const [writable, setWritable] = useState(false);
  const [error, setError] = useState('');
  const [status, setStatus] = useState('');
  const rawRef = useRef<string | null>(null);

  useEffect(() => {
    try {
      const raw = window.localStorage.getItem(contentCalendarStorageKey(profileId));
      setPosts(restoreContentCalendar(raw, profileId));
      rawRef.current = raw;
      setWritable(true);
      setError('');
    } catch (e) {
      setPosts([]);
      setWritable(false);
      setError(e instanceof Error ? e.message : 'Saved content calendar could not be read. Nothing was overwritten.');
    }
    try { setOffers(restoreLocalOffers(window.localStorage.getItem(offerStorageKey(profileId)), profile) ?? []); } catch { setOffers([]); }
    setReady(true);
  }, [profileId, profile]);

  const problems = useMemo(() => (editing ? validatePost(editing) : []), [editing]);
  const visible = useMemo(() => groupByMonthAndDay(filter === 'all' ? posts : posts.filter(p => p.status === filter)), [posts, filter]);
  const counts = useMemo(() => countsByStatus(posts), [posts]);

  function commit(next: ContentPost[], message: string) {
    try {
      rawRef.current = persistContentCalendar(window.localStorage, profileId, rawRef.current, next);
      setPosts(next); setError(''); setStatus(message); return true;
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Could not save. Your changes remain.'); return false;
    }
  }
  function save() {
    if (!editing) return;
    try {
      if (commit(savePost(posts, editing), 'Post saved in this browser.')) setEditing(null);
    } catch (e) { setError(e instanceof Error ? e.message : 'Post is not valid.'); }
  }
  function remove(id: string) {
    if (!window.confirm('Delete this post draft?')) return;
    commit(removePost(posts, id), 'Post deleted.');
  }

  if (!ready) return <p role="status">Loading content calendar…</p>;
  const limit = editing ? platformGuidance[editing.platform] : 0;
  return <section aria-labelledby="content-calendar-title" data-testid="content-calendar">
    <div className="section-heading">
      <h2 id="content-calendar-title">Content calendar</h2>
      <span className="status-badge">Browser draft · not published</span>
    </div>
    <p className="panel-note">Write posts yourself, pick a platform and a planned date. Nothing is published, scheduled or generated by AI.</p>
    {status && <p role="status" className="activity-status" data-testid="content-calendar-status">{status}</p>}
    {error && <p role="alert" className="error" data-testid="content-calendar-error">{error}</p>}
    <p data-testid="content-calendar-counts">{posts.length} of 100 posts · {contentStatuses.map(s => `${counts[s]} ${statusLabel[s].toLowerCase()}`).join(' · ')}</p>
    {!editing && <button type="button" className="primary-button" disabled={!writable} data-testid="content-calendar-add" onClick={() => { setEditing(blankPost(newId())); setStatus(''); }}>Add post</button>}
    {editing && <form data-testid="content-calendar-form" onSubmit={e => { e.preventDefault(); save(); }}>
      <fieldset>
        <legend>{posts.some(p => p.id === editing.id) ? 'Edit post' : 'New post'}</legend>
        <label>Platform<select value={editing.platform} onChange={e => setEditing({ ...editing, platform: e.target.value as ContentPost['platform'] })}>{contentPlatforms.map(p => <option key={p} value={p}>{p}</option>)}</select></label>
        <label>Planned date<input type="date" value={editing.plannedDate} onChange={e => setEditing({ ...editing, plannedDate: e.target.value })} /></label>
        <label>Title<input value={editing.title} maxLength={contentTitleLimit} onChange={e => setEditing({ ...editing, title: e.target.value })} /></label>
        <label>Post text<textarea rows={6} value={editing.body} onChange={e => setEditing({ ...editing, body: e.target.value })} /></label>
        <p className="panel-note" data-testid="content-calendar-counter">{editing.body.length} / {contentBodyLimit} characters. {editing.platform} guidance: about {limit} (a guide only, not enforced).</p>
        <label>Status<select value={editing.status} onChange={e => setEditing({ ...editing, status: e.target.value as ContentStatus })}>{contentStatuses.map(s => <option key={s} value={s}>{statusLabel[s]}</option>)}</select></label>
        {offers.length > 0 && <label>Related offer (optional)<select value={editing.linkedOfferId ?? ''} onChange={e => { const next: ContentPost = { ...editing, linkedOfferId: e.target.value }; if (!e.target.value) delete next.linkedOfferId; setEditing(next); }}><option value="">None</option>{offers.map(o => <option key={o.id} value={o.id}>{o.name}</option>)}</select></label>}
        {problems.length > 0 && <ul role="status" data-testid="content-calendar-validation">{problems.map(p => <li key={p}>{p}</li>)}</ul>}
        <button type="submit" className="primary-button" disabled={!writable || problems.length > 0} data-testid="content-calendar-save">Save post</button>
        <button type="button" onClick={() => setEditing(null)}>Cancel</button>
      </fieldset>
    </form>}
    <label>Show<select value={filter} onChange={e => setFilter(e.target.value as 'all' | ContentStatus)} data-testid="content-calendar-filter"><option value="all">All statuses</option>{contentStatuses.map(s => <option key={s} value={s}>{statusLabel[s]}</option>)}</select></label>
    {posts.length === 0 && <p className="panel-note" data-testid="content-calendar-empty">No posts yet. Add your first post idea above.</p>}
    {posts.length > 0 && visible.length === 0 && <p className="panel-note">No posts with that status.</p>}
    {visible.map(month => <div key={month.month}>
      <h3>{new Date(`${month.month}-01T00:00:00Z`).toLocaleDateString('en-AU', { month: 'long', year: 'numeric', timeZone: 'UTC' })}</h3>
      {month.days.map(day => <div key={day.date}>
        <h4>{new Date(`${day.date}T00:00:00Z`).toLocaleDateString('en-AU', { weekday: 'short', day: 'numeric', month: 'short', timeZone: 'UTC' })}</h4>
        <ul className="local-offer-list">{day.posts.map(p => <li key={p.id} className="local-offer" data-testid="content-calendar-post">
          <strong>{p.title}</strong> <span className="status-badge">{p.platform}</span> <span className="status-badge">{statusLabel[p.status]}</span> <span className="panel-note">Browser draft · not published</span>
          {p.body && <p>{p.body.length > 160 ? `${p.body.slice(0, 160)}…` : p.body}</p>}
          <button type="button" disabled={!writable} onClick={() => { setEditing({ ...p }); setStatus(''); }}>Edit</button>
          <button type="button" disabled={!writable} onClick={() => remove(p.id)}>Delete</button>
        </li>)}</ul>
      </div>)}
    </div>)}
  </section>;
}
