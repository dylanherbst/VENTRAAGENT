'use client';
import { useEffect, useMemo, useRef, useState } from 'react';
import { audienceNoteLimit, blankCampaign, blankStep, bodyLimit, campaignKinds, campaignLimit, campaignNameLimit, campaignStatuses, countsByStatus, emailCampaignsStorageKey, maxWaitDays, persistEmailCampaigns, preheaderLimit, removeCampaign, restoreEmailCampaigns, saveCampaign, sequenceTimeline, stepLimit, subjectLimit, timelineLabel, validateCampaign } from '../../lib/local-email-campaigns';
import type { CampaignStatus, CampaignStep, EmailCampaign } from '../../lib/local-email-campaigns';
import type { Profile } from '../../lib/onboarding';

const statusLabel: Record<CampaignStatus, string> = { draft: 'Draft', ready: 'Ready', archived: 'Archived' };
const kindLabel = { 'one-off': 'One-off email', nurture: 'Nurture sequence' } as const;
const newId = () => (typeof crypto !== 'undefined' && 'randomUUID' in crypto ? crypto.randomUUID() : `c-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`);

export default function EmailCampaigns({ profile }: { profile: Pick<Profile, 'id'> }) {
  const profileId = profile.id;
  const [campaigns, setCampaigns] = useState<EmailCampaign[]>([]);
  const [editing, setEditing] = useState<EmailCampaign | null>(null);
  const [filter, setFilter] = useState<'all' | CampaignStatus>('all');
  const [ready, setReady] = useState(false);
  const [writable, setWritable] = useState(false);
  const [error, setError] = useState('');
  const [status, setStatus] = useState('');
  const rawRef = useRef<string | null>(null);

  useEffect(() => {
    try {
      const raw = window.localStorage.getItem(emailCampaignsStorageKey(profileId));
      setCampaigns(restoreEmailCampaigns(raw, profileId));
      rawRef.current = raw;
      setWritable(true);
      setError('');
    } catch (e) {
      setCampaigns([]);
      setWritable(false);
      setError(e instanceof Error ? e.message : 'Saved email campaigns could not be read. Nothing was overwritten.');
    }
    setReady(true);
  }, [profileId]);

  const check = useMemo(() => (editing ? validateCampaign(editing) : { problems: [], warnings: [] }), [editing]);
  const visible = useMemo(() => (filter === 'all' ? campaigns : campaigns.filter(c => c.status === filter)), [campaigns, filter]);
  const counts = useMemo(() => countsByStatus(campaigns), [campaigns]);

  function commit(next: EmailCampaign[], message: string) {
    try {
      rawRef.current = persistEmailCampaigns(window.localStorage, profileId, rawRef.current, next);
      setCampaigns(next); setError(''); setStatus(message); return true;
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Could not save. Your changes remain.'); return false;
    }
  }
  function save() {
    if (!editing) return;
    try { if (commit(saveCampaign(campaigns, editing), 'Campaign saved in this browser.')) setEditing(null); }
    catch (e) { setError(e instanceof Error ? e.message : 'Campaign is not valid.'); }
  }
  function remove(id: string) {
    if (!window.confirm('Delete this campaign draft?')) return;
    commit(removeCampaign(campaigns, id), 'Campaign deleted.');
  }
  const patchStep = (id: string, patch: Partial<CampaignStep>) => editing && setEditing({ ...editing, steps: editing.steps.map(s => (s.id === id ? { ...s, ...patch } : s)) });

  if (!ready) return <p role="status">Loading email campaigns…</p>;
  return <section aria-labelledby="email-campaigns-title" data-testid="email-campaigns">
    <div className="section-heading">
      <h2 id="email-campaigns-title">Email campaigns and nurture sequences</h2>
      <span className="status-badge">Browser draft · nothing is sent</span>
    </div>
    <p className="panel-note">Write emails yourself for an audience you choose. Nothing is sent, scheduled with a provider or generated by AI, and no email addresses are contacted.</p>
    {status && <p role="status" className="activity-status" data-testid="email-campaigns-status">{status}</p>}
    {error && <p role="alert" className="error" data-testid="email-campaigns-error">{error}</p>}
    <p data-testid="email-campaigns-counts">{campaigns.length} of {campaignLimit} campaigns · {campaignStatuses.map(s => `${counts[s]} ${statusLabel[s].toLowerCase()}`).join(' · ')}</p>
    {!editing && <button type="button" className="primary-button" disabled={!writable} data-testid="email-campaigns-add" onClick={() => { setEditing(blankCampaign(newId(), newId())); setStatus(''); }}>Add campaign</button>}
    {editing && <form data-testid="email-campaigns-form" onSubmit={e => { e.preventDefault(); save(); }}>
      <fieldset>
        <legend>{campaigns.some(c => c.id === editing.id) ? 'Edit campaign' : 'New campaign'}</legend>
        <label>Name<input value={editing.name} maxLength={campaignNameLimit} data-testid="email-campaigns-name" onChange={e => setEditing({ ...editing, name: e.target.value })} /></label>
        <label>Type<select value={editing.kind} onChange={e => setEditing({ ...editing, kind: e.target.value as EmailCampaign['kind'] })}>{campaignKinds.map(k => <option key={k} value={k}>{kindLabel[k]}</option>)}</select></label>
        <label>Audience note<textarea rows={3} value={editing.audienceNote} maxLength={audienceNoteLimit} data-testid="email-campaigns-audience" onChange={e => setEditing({ ...editing, audienceNote: e.target.value })} /></label>
        <p className="panel-note">Describe who this is for, for example &quot;warm leads who opted in to my newsletter&quot;. Nothing is looked up.</p>
        <label>Status<select value={editing.status} onChange={e => setEditing({ ...editing, status: e.target.value as CampaignStatus })}>{campaignStatuses.map(s => <option key={s} value={s}>{statusLabel[s]}</option>)}</select></label>
        {editing.steps.map((s, i) => <fieldset key={s.id} data-testid="email-campaigns-step">
          <legend>Email {i + 1}</legend>
          {i === 0 ? <p className="panel-note">Sent on day 0 (the start).</p> : <label>Wait after the previous email (days)<input type="number" min={0} max={maxWaitDays} value={s.waitDays} onChange={e => patchStep(s.id, { waitDays: e.target.value === '' ? 0 : Number(e.target.value) })} /></label>}
          <label>Subject<input value={s.subject} maxLength={subjectLimit} onChange={e => patchStep(s.id, { subject: e.target.value })} /></label>
          <label>Preview text (optional)<input value={s.preheader ?? ''} maxLength={preheaderLimit} onChange={e => patchStep(s.id, { preheader: e.target.value })} /></label>
          <label>Body<textarea rows={6} value={s.body} onChange={e => patchStep(s.id, { body: e.target.value })} /></label>
          <p className="panel-note">{s.body.length} / {bodyLimit} characters</p>
          {editing.steps.length > 1 && <button type="button" onClick={() => setEditing({ ...editing, steps: editing.steps.filter(x => x.id !== s.id) })}>Remove email {i + 1}</button>}
        </fieldset>)}
        <button type="button" disabled={editing.steps.length >= stepLimit} data-testid="email-campaigns-add-step" onClick={() => setEditing({ ...editing, steps: [...editing.steps, blankStep(newId(), 3)] })}>Add email ({editing.steps.length} of {stepLimit})</button>
        <p data-testid="email-campaigns-timeline">Timeline: {timelineLabel(editing)}</p>
        {check.problems.length > 0 && <ul role="status" data-testid="email-campaigns-validation">{check.problems.map(p => <li key={p}>{p}</li>)}</ul>}
        {check.warnings.length > 0 && <ul className="panel-note" data-testid="email-campaigns-warnings">{check.warnings.map(w => <li key={w}>Note: {w}</li>)}</ul>}
        <button type="submit" className="primary-button" disabled={!writable || check.problems.length > 0} data-testid="email-campaigns-save">Save campaign</button>
        <button type="button" onClick={() => setEditing(null)}>Cancel</button>
      </fieldset>
    </form>}
    <label>Show<select value={filter} onChange={e => setFilter(e.target.value as 'all' | CampaignStatus)} data-testid="email-campaigns-filter"><option value="all">All statuses</option>{campaignStatuses.map(s => <option key={s} value={s}>{statusLabel[s]}</option>)}</select></label>
    {campaigns.length === 0 && <p className="panel-note" data-testid="email-campaigns-empty">No campaigns yet. Add your first one above.</p>}
    {campaigns.length > 0 && visible.length === 0 && <p className="panel-note">No campaigns with that status.</p>}
    <ul className="local-offer-list">{visible.map(c => <li key={c.id} className="local-offer" data-testid="email-campaigns-item">
      <strong>{c.name}</strong> <span className="status-badge">{kindLabel[c.kind]}</span> <span className="status-badge">{statusLabel[c.status]}</span> <span className="panel-note">Browser draft · nothing is sent</span>
      <p>{c.steps.length} {c.steps.length === 1 ? 'email' : 'emails'} · {timelineLabel(c)}</p>
      {c.audienceNote && <p className="panel-note">Audience: {c.audienceNote}</p>}
      <ol>{sequenceTimeline(c).map(t => <li key={t.step.id}>Day {t.dayOffset}: {t.step.subject}</li>)}</ol>
      <button type="button" disabled={!writable} onClick={() => { setEditing({ ...c, steps: c.steps.map(s => ({ ...s })) }); setStatus(''); }}>Edit</button>
      <button type="button" disabled={!writable} onClick={() => remove(c.id)}>Delete</button>
    </li>)}</ul>
  </section>;
}
